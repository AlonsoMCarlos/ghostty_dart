// Renders COMPATIBILITY.md from a Comparison. The output depends only on the
// snapshot, the adapter's sources and the status file (no dates, no paths),
// so `compat:check` can compare it byte for byte.

import 'compare.dart';
import 'model.dart';

/// Enums with more values than this collapse into one row when every value
/// has the same status and no note (TerminalKey has 273).
const _collapseValuesAbove = 12;

const _migratingUrl =
    'https://github.com/AlonsoMCarlos/ghostty_dart/blob/main/packages/'
    'ghostty_dart_xterm/MIGRATING_FROM_XTERM.md';

String _cell(String text) =>
    text.replaceAll('|', r'\|').replaceAll('\n', ' ').trim();

String _memberLabel(ApiSymbol symbol, ApiMember member) =>
    switch (member.kind) {
      'constructor' =>
        member.name == 'new'
            ? '`${symbol.name}()`'
            : '`${symbol.name}.${member.name}()`',
      'method' || 'operator' => '`${member.name}()`',
      _ => '`${member.name}`',
    };

String _kindLabel(ApiMember member) => switch (member.kind) {
  'property' => member.sig['static'] == true ? 'static property' : 'property',
  'method' => member.sig['static'] == true ? 'static method' : 'method',
  _ => member.kind,
};

/// The Markdown report.
String renderReport(Comparison comparison) {
  final out = StringBuffer()
    ..writeln(
      '<!-- Generated by tool/xterm_compat (`mise run compat`). Do not edit by '
      'hand: change tool/xterm_compat/status.json or the adapter, then '
      'regenerate. `mise run compat:check` fails when this file is stale. -->',
    )
    ..writeln()
    ..writeln('# Compatibility with xterm 4.0.0')
    ..writeln()
    ..writeln(
      '`ghostty_dart_xterm` offers the public API of '
      '[`xterm`](https://pub.dev/packages/xterm) 4.0.0 on top of '
      'libghostty-vt, so that most apps move by changing their import. It is '
      'not a drop-in replacement: this file lists, member by member, what is '
      'the same and what is not, and it is regenerated and checked in CI on '
      'every change. For what the differences mean in practice, with code, '
      'read the [migration guide]($_migratingUrl).',
    )
    ..writeln()
    ..writeln('## How this list is made')
    ..writeln()
    ..writeln(
      'Every public symbol and member of `package:xterm` 4.0.0 (the '
      'libraries `xterm.dart`, `core.dart`, `ui.dart`, `zmodem.dart`, '
      '`suggestion.dart` and `utils.dart`), and its status in '
      '`ghostty_dart_xterm`. The list of xterm members comes from the '
      'analyzer, run on the published xterm 4.0.0 sources; presence and '
      'signatures on our side come from the analyzer too, so a renamed '
      'parameter, a changed default or a missing member shows up here '
      'automatically. Behaviour differences the analyzer cannot see are '
      'recorded by hand with a reason.',
    )
    ..writeln()
    ..writeln('| Status | Meaning |')
    ..writeln('|---|---|')
    ..writeln(
      '| ${Status.same.icon} | Same: present with the same signature '
      '(name, parameters, defaults, types). |',
    )
    ..writeln(
      '| ${Status.differs.icon} | Differs: present, but its signature or '
      'behaviour differs; the note says how. |',
    )
    ..writeln(
      '| ${Status.missing.icon} | Missing: not provided yet. Without a note, '
      'it is planned. |',
    )
    ..writeln(
      '| ${Status.wont.icon} | Won\'t support: not provided, on purpose; the '
      'note says why. |',
    )
    ..writeln()
    ..writeln(
      'Members inherited from Flutter or SDK types (for example '
      '`ChangeNotifier`) are not listed. A symbol is listed under the first '
      'library that exports it; `xterm.dart` re-exports `core.dart`, `ui.dart` '
      'and `zmodem.dart`. Additions that xterm does not have are listed at the '
      'end.',
    )
    ..writeln()
    ..writeln(
      'Most ⚠️ notes describe behaviour, not signatures: the member exists and '
      'is called the same way, but the engine underneath is libghostty-vt, '
      'not xterm\'s Dart emulator. The notes cite the ADR that decided each '
      'difference where there is one '
      '([ADR 0013](https://github.com/AlonsoMCarlos/ghostty_dart/blob/main/'
      'docs/internal/adr/0013-xterm-adapter-design.md)).',
    )
    ..writeln();

  // Summary.
  final byLibrary = <String, Map<Status, int>>{};
  for (final row in comparison.rows) {
    final counts = byLibrary.putIfAbsent(
      row.symbol.primaryLibrary,
      () => {for (final s in Status.values) s: 0},
    );
    counts[row.status] = counts[row.status]! + 1;
  }
  out
    ..writeln('## Summary')
    ..writeln()
    ..writeln(
      'Symbols and members per library (a symbol counts once, plus one per '
      'member).',
    )
    ..writeln()
    ..writeln(
      '| Library | ${Status.values.map((s) => s.icon).join(' | ')} | Total |',
    )
    ..writeln('|---|${'---:|' * (Status.values.length + 1)}');
  final totals = {for (final s in Status.values) s: 0};
  for (final lib in libraryOrder) {
    final counts = byLibrary[lib];
    if (counts == null) continue;
    final total = counts.values.fold(0, (a, b) => a + b);
    out.writeln(
      '| `$lib` | ${Status.values.map((s) => counts[s]).join(' | ')} | '
      '$total |',
    );
    for (final s in Status.values) {
      totals[s] = totals[s]! + counts[s]!;
    }
  }
  out
    ..writeln(
      '| **All** | ${Status.values.map((s) => '**${totals[s]}**').join(' | ')}'
      ' | **${totals.values.fold(0, (a, b) => a + b)}** |',
    )
    ..writeln()
    ..writeln('Additions beyond xterm: ${comparison.additions.length}.')
    ..writeln();

  // One section per library, one table per symbol.
  for (final lib in libraryOrder) {
    final rows = comparison.rows
        .where((r) => r.symbol.primaryLibrary == lib)
        .toList();
    if (rows.isEmpty) continue;
    out
      ..writeln('## `$lib`')
      ..writeln();
    var i = 0;
    while (i < rows.length) {
      final head = rows[i];
      final members = <Row>[];
      i++;
      while (i < rows.length && rows[i].member != null) {
        members.add(rows[i]);
        i++;
      }
      _symbolSection(out, head, members);
    }
  }

  out
    ..writeln('## Additions beyond xterm')
    ..writeln();
  if (comparison.additions.isEmpty) {
    out
      ..writeln('None yet.')
      ..writeln();
  } else {
    out
      ..writeln('| Member | Kind |')
      ..writeln('|---|---|');
    final keys = comparison.additions.keys.toList()..sort();
    for (final key in keys) {
      out.writeln('| `$key` | ${comparison.additions[key]} |');
    }
    out.writeln();
  }
  // One newline at the end of the file.
  return '${out.toString().trimRight()}\n';
}

void _symbolSection(StringBuffer out, Row head, List<Row> members) {
  final symbol = head.symbol;
  out
    ..writeln('### `${symbol.name}`')
    ..writeln()
    ..write(
      '${symbol.kind}, `${symbol.source}`. ${head.status.icon} '
      '${head.status.label}',
    );
  if (head.note.isNotEmpty) out.write(': ${_cell(head.note)}');
  out
    ..writeln('.')
    ..writeln();
  if (members.isEmpty) return;
  out
    ..writeln('| Member | Kind | Status | Notes |')
    ..writeln('|---|---|---|---|');
  final values = members.where((r) => r.member!.kind == 'value').toList();
  final collapse =
      values.length > _collapseValuesAbove &&
      values.every((r) => r.status == values.first.status && r.note.isEmpty);
  if (collapse) {
    out.writeln(
      '| `${values.first.member!.name}` … `${values.last.member!.name}` | '
      '${values.length} values | ${values.first.status.icon} | same names, '
      'same order (`index`) |',
    );
  }
  for (final row in members) {
    final member = row.member!;
    if (collapse && member.kind == 'value') continue;
    out.writeln(
      '| ${_memberLabel(symbol, member)} | ${_kindLabel(member)} | '
      '${row.status.icon} | ${_cell(row.note)} |',
    );
  }
  out.writeln();
}
