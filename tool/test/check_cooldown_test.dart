// Tests for tool/check_cooldown.dart (lock parsing and lockfile discovery;
// the pub.dev lookups need network and are exercised by `mise run cooldown`).
// Run with `dart tool/test/check_cooldown_test.dart` from the repository root.
//
// The same tiny harness as tool/test/check_translations_test.dart: the
// workspace root (which owns tool/) has no package:test (only lints, plus
// analyzer and crypto for tool/xterm_compat).

import 'dart:io';

import '../check_cooldown.dart';

var _passed = 0;
final _failed = <String>[];
final _temps = <Directory>[];

void test(String name, void Function() body) {
  try {
    body();
    _passed++;
    stdout.writeln('ok   $name');
  } catch (e, s) {
    _failed.add(name);
    stdout.writeln(
      'FAIL $name\n  $e\n${s.toString().split('\n').take(4).join('\n')}',
    );
  }
}

void expect(bool condition, String what) {
  if (!condition) throw StateError('expected: $what');
}

void expectThrows<T extends Object>(void Function() body, String what) {
  try {
    body();
  } on T {
    return;
  }
  throw StateError('expected $T: $what');
}

const _lock = '''
# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  args:
    dependency: transitive
    description:
      name: args
      sha256: "d0481093c50b1da8910eb0bb301626d4d8eb7284aa739614d2b394ee09e3ea04"
      url: "https://pub.dev"
    source: hosted
    version: "2.7.0"
  ghostty_dart:
    dependency: transitive
    description:
      path: "packages/ghostty_dart"
      relative: true
    source: path
    version: "0.1.0"
  lints:
    dependency: "direct dev"
    description:
      name: lints
      sha256: a5e2b223cb7c9c8efdc663ef484fdd95bb243bff242ef5b13e26883547fce9a0
      url: "https://pub.dev"
    source: hosted
    version: "6.1.0"
  sky_engine:
    dependency: transitive
    description: flutter
    source: sdk
    version: "0.0.0"
sdks:
  dart: ">=3.11.0 <4.0.0"
''';

/// A fresh git repository with [files] (path -> content) written into it.
String _repo(Map<String, String> files) {
  final dir = Directory.systemTemp.createTempSync('check_cooldown_');
  _temps.add(dir);
  final init = Process.runSync('git', [
    'init',
    '-q',
  ], workingDirectory: dir.path);
  if (init.exitCode != 0) throw StateError('git init: ${init.stderr}');
  files.forEach((path, content) {
    File('${dir.path}/$path')
      ..createSync(recursive: true)
      ..writeAsStringSync(content);
  });
  return dir.path;
}

void main() {
  test('parses only hosted entries', () {
    final parsed = parseLock(_lock, 'pubspec.lock');
    expect(
      parsed.length == 2 &&
          parsed['args'] == '2.7.0' &&
          parsed['lints'] == '6.1.0',
      'args and lints only: $parsed',
    );
  });

  test('CRLF line endings parse the same', () {
    final parsed = parseLock(_lock.replaceAll('\n', '\r\n'), 'pubspec.lock');
    expect(parsed.length == 2, 'two entries: $parsed');
  });

  test('a hosted entry the regex cannot read fails closed', () {
    // `version` before `source`: a format the regex does not understand.
    final reordered = _lock.replaceFirst(
      '    source: hosted\n    version: "2.7.0"',
      '    version: "2.7.0"\n    source: hosted',
    );
    expectThrows<FormatException>(
      () => parseLock(reordered, 'pubspec.lock'),
      'count mismatch',
    );
  });

  test('a lockfile with no hosted entry fails closed', () {
    expectThrows<FormatException>(
      () => parseLock('packages: {}\n', 'pubspec.lock'),
      'zero entries',
    );
  });

  test('finds tracked and untracked lockfiles, not ignored ones', () {
    final root = _repo({
      'pubspec.lock': _lock,
      'tool/pana/pubspec.lock': _lock,
      'build/pubspec.lock': _lock,
      '.gitignore': 'build/\n',
    });
    final found = findLockfiles(root);
    expect(
      found.length == 2 &&
          found[0] == 'pubspec.lock' &&
          found[1] == 'tool/pana/pubspec.lock',
      'root and tool/pana only: $found',
    );
  });

  test('a repo without a root pubspec.lock fails', () {
    final root = _repo({'tool/pana/pubspec.lock': _lock});
    expectThrows<StateError>(() => findLockfiles(root), 'missing root lock');
  });

  for (final dir in _temps) {
    dir.deleteSync(recursive: true);
  }
  stdout.writeln('\n$_passed passed, ${_failed.length} failed');
  if (_failed.isNotEmpty) exitCode = 1;
}
