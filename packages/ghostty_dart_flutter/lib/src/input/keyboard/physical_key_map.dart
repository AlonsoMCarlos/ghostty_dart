/// The libghostty-vt key for a Flutter physical key (ADR 0011, Input).
///
/// Both follow the W3C UI Events `KeyboardEvent.code` names over USB HID
/// usages, so the mapping is static and does not depend on the keyboard
/// layout: the key labelled "ф" on a Russian layout is [VtKey.a]. Keys
/// libghostty-vt does not know become [VtKey.unidentified]. Never exported.
VtKey vtKeyForPhysicalKey(PhysicalKeyboardKey key) =>
    physicalKeyToVtKey[key] ?? VtKey.unidentified;

