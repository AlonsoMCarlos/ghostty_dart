// Regenerates lib/src/ffi/bindings.g.dart from the libghostty-vt headers.
//
// Usage (from the repo root, after tool/native/build.sh):
//   dart run packages/ghostty_vt/tool/ffigen.dart [include-dir]
//
// The include dir defaults to the Linux x64 build output. Requires libclang.

import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main(List<String> args) async {
  final packageRoot = Platform.script.resolve('../');
  final repoRoot = packageRoot.resolve('../../');
  final include = args.isNotEmpty
      ? Directory(args.first).absolute.uri
      : repoRoot.resolve('.native-cache/out/x86_64-linux-gnu/include/');

  bool isGhostty(String name) =>
      name.startsWith('ghostty_') || name.startsWith('Ghostty');

  final generator = FfiGenerator(
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/ffi/bindings.g.dart'),
      ),
      preamble: '''
// Generated by packages/ghostty_vt/tool/ffigen.dart from libghostty-vt
// headers. Do not edit by hand.
// ignore_for_file: type=lint, unused_field
''',
      style: const NativeExternalBindings(),
    ),
    input: Input(
      entryPoints: [include.resolve('ghostty/vt.h')],
      include: (header) => header.path.contains('/ghostty/'),
      compilerOptions: ['-I${include.toFilePath()}'],
      appendCompilerOptions: true,
    ),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = isGhostty(node.originalName),
        struct: (node) => node.isIncluded = isGhostty(node.originalName),
        union: (node) => node.isIncluded = isGhostty(node.originalName),
        enumClass: (node) {
          node.isIncluded = isGhostty(node.originalName);
          // Every libghostty-vt enum ends with a sentinel set to INT_MAX
          // (GHOSTTY_ENUM_MAX_VALUE, include/ghostty/vt/types.h), which pins
          // its size to `int` on every supported compiler.
          node.silenceWarning = true;
          // Minor releases may add enum values (ABI policy), and Dart enums
          // throw on unknown values. Raw bindings use ints; the public API
          // maps them to Dart enums that tolerate unknown values.
          node.style = EnumStyle.intConstants;
        },
        typealias: (node) => node.isIncluded = isGhostty(node.originalName)
            ? TypealiasInclude.always
            : TypealiasInclude.ifUsed,
        macroConstant: (node) =>
            node.isIncluded = node.originalName.startsWith('GHOSTTY_'),
      ),
    ],
  );
  // Prefer an explicit LIBCLANG_PATH; ffigen's own lookup shells out to
  // ldconfig, which is often not on a user's PATH.
  final libclang = Platform.environment['LIBCLANG_PATH'];
  await generator.generate(
    libclangDylib: libclang == null ? null : Uri.file(libclang),
  );
}
